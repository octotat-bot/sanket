"""Per-frame features and fixed-length resampling (spec "normalization.features_v1", ADR 008).

The single reference implementation. `web/src/lib/inference/features.ts` mirrors it line for line
and must reproduce `spec/golden/features_v1.json` (generated by `sanket.keypoints.golden`).

Pipeline for one clip (the stored arrays of one video, or a live buffer in the browser):

1. short gaps (raw landmarks): a part (pose, left hand, right hand) missing for ≤ max_gap_frames
   frames between two present frames is filled by linear interpolation of its raw landmarks (by
   timestamp) and marked present. Done on raw landmarks so derived parts stay consistent.
2. per frame: aspect-correct (x * W/H) with the *processed* frame size, then
   - pose points with visibility < pose_visibility_min count as missing (zeros);
   - body-relative = (p - shoulder midpoint) / shoulder width, for the chosen pose points and
     both hands (only if the shoulders are usable; otherwise the frame has no body frame);
   - hand-local = (p - wrist) / palm size (wrist→middle-finger MCP), per hand;
   - presence = [pose, left, right] as 0/1. Missing parts are zeros, never NaN. A hand's
     body-relative columns are valid only if both that hand and the pose are present.
3. resample to T frames at evenly spaced times between the first and last timestamp: linear
   between the two neighbouring frames if both have the part, else the nearest frame's values.
4. optional velocities: frame-to-frame differences of the coordinate features, zero where the
   part is missing at either end.
"""

from dataclasses import dataclass
from typing import Any

import numpy as np

from sanket.keypoints.normalize import L_SHOULDER, R_SHOULDER, aspect_correct
from sanket.spec import load_spec


@dataclass(frozen=True)
class FeatureSpec:
    pose_idx: tuple[int, ...]
    vis_min: float
    wrist: int
    mcp: int
    max_gap: int
    T: int

    @staticmethod
    def from_spec(spec: dict[str, Any] | None = None) -> "FeatureSpec":
        f = (spec or load_spec())["normalization"]["features_v1"]
        return FeatureSpec(
            pose_idx=tuple(f["pose_feature_indices"]),
            vis_min=float(f["pose_visibility_min"]),
            wrist=int(f["palm"]["wrist"]),
            mcp=int(f["palm"]["middle_mcp"]),
            max_gap=int(f["max_gap_frames"]),
            T=int(f["resample"]["T"]),
        )

    @property
    def parts(self) -> dict[str, slice]:
        """Column ranges of each part's coordinate features (presence is the last 3 columns)."""
        npose = 2 * len(self.pose_idx)
        return {
            "pose": slice(0, npose),
            "left": slice(npose, npose + 42),  # left_body
            "right": slice(npose + 42, npose + 84),
            "left_local": slice(npose + 84, npose + 126),
            "right_local": slice(npose + 126, npose + 168),
        }

    @property
    def n_coord(self) -> int:
        return 2 * len(self.pose_idx) + 168

    @property
    def n_features(self) -> int:
        return self.n_coord + 3


# Presence flags each part's columns depend on (all must be 1 for the part to be valid).
_PART_DEPS: dict[str, tuple[int, ...]] = {
    "pose": (0,),
    "left": (1, 0),
    "right": (2, 0),
    "left_local": (1,),
    "right_local": (2,),
}


def frame_features(
    pose: np.ndarray,
    left: np.ndarray,
    right: np.ndarray,
    present: tuple[bool, bool, bool],
    width: int,
    height: int,
    fs: FeatureSpec,
) -> np.ndarray:
    """One frame → (n_features,) float64. `pose` (25, 4) x,y,z,vis; hands (21, 3); normalized."""
    out = np.zeros(fs.n_features)
    pose_ok, left_ok, right_ok = present
    parts = fs.parts
    body: tuple[np.ndarray, float] | None = None
    if pose_ok:
        p = aspect_correct(pose[:, :2], width, height)
        vis = pose[:, 3]
        if vis[L_SHOULDER] >= fs.vis_min and vis[R_SHOULDER] >= fs.vis_min:
            mid = (p[L_SHOULDER] + p[R_SHOULDER]) / 2
            sw = float(np.linalg.norm(p[L_SHOULDER] - p[R_SHOULDER]))
            if sw > 1e-6:
                body = (mid, sw)
                sel = np.array(fs.pose_idx)
                rel = (p[sel] - mid) / sw
                rel[vis[sel] < fs.vis_min] = 0.0  # low-visibility points count as missing
                out[parts["pose"]] = rel.ravel()
    flags = [body is not None, False, False]
    for k, (hand, ok) in enumerate(((left, left_ok), (right, right_ok)), start=1):
        if not ok:
            continue
        side = "left" if k == 1 else "right"
        h = aspect_correct(hand[:, :2], width, height)
        palm = float(np.linalg.norm(h[fs.mcp] - h[fs.wrist]))
        if palm <= 1e-6:
            continue  # degenerate hand: treat as missing
        flags[k] = True
        out[parts[f"{side}_local"]] = ((h - h[fs.wrist]) / palm).ravel()
        if body is not None:
            out[parts[side]] = ((h - body[0]) / body[1]).ravel()
    out[fs.n_coord :] = np.array(flags, dtype=np.float64)
    return out


def clip_features(clip: dict[str, np.ndarray], fs: FeatureSpec) -> np.ndarray:
    """All frames of a clip (stored .npz layout) → (n_frames, n_features)."""
    w, h = (int(v) for v in clip["frame_size"])
    return np.stack(
        [
            frame_features(
                clip["pose"][i],
                clip["left"][i],
                clip["right"][i],
                (
                    bool(clip["pose_present"][i]),
                    bool(clip["left_present"][i]),
                    bool(clip["right_present"][i]),
                ),
                w,
                h,
                fs,
            )
            for i in range(len(clip["t_ms"]))
        ]
    )


def _parts_with_deps(fs: FeatureSpec) -> list[tuple[slice, tuple[int, ...]]]:
    return [(sl, _PART_DEPS[name]) for name, sl in fs.parts.items()]


def _valid(row: np.ndarray, deps: tuple[int, ...], fs: FeatureSpec) -> bool:
    return all(row[fs.n_coord + d] > 0.5 for d in deps)


def fill_short_gaps(clip: dict[str, np.ndarray], max_gap: int) -> dict[str, np.ndarray]:
    """Raw landmarks: fill runs of ≤ max_gap missing frames bounded by present frames, per part."""
    out = {k: np.array(v, copy=True) for k, v in clip.items()}
    t = out["t_ms"].astype(np.float64)
    n = len(t)
    for arr_key, flag_key in (
        ("pose", "pose_present"),
        ("left", "left_present"),
        ("right", "right_present"),
    ):
        present = out[flag_key].astype(bool)
        i = 0
        while i < n:
            if present[i]:
                i += 1
                continue
            j = i
            while j < n and not present[j]:
                j += 1
            if i > 0 and j < n and (j - i) <= max_gap:
                a, b = i - 1, j
                for g in range(i, j):
                    w = (t[g] - t[a]) / (t[b] - t[a])
                    out[arr_key][g] = (1 - w) * out[arr_key][a] + w * out[arr_key][b]
                    out[flag_key][g] = True
            i = j
    return out


def resample(
    feats: np.ndarray, t_ms: np.ndarray, fs: FeatureSpec, T: int | None = None
) -> np.ndarray:
    """(n, F) at timestamps t_ms → (T, F) at T evenly spaced times."""
    T = T or fs.T
    n = len(feats)
    if n == 0:
        raise ValueError("empty clip")
    if n == 1:
        return np.repeat(feats, T, axis=0)
    t = t_ms.astype(np.float64)
    targets = np.linspace(t[0], t[-1], T)
    out = np.zeros((T, feats.shape[1]))
    for k, tt in enumerate(targets):
        j = int(np.searchsorted(t, tt, side="right"))
        a, b = max(j - 1, 0), min(j, n - 1)
        w = 0.0 if b == a else (tt - t[a]) / (t[b] - t[a])
        nearest = a if w < 0.5 else b
        for sl, deps in _parts_with_deps(fs):
            if _valid(feats[a], deps, fs) and _valid(feats[b], deps, fs):
                out[k, sl] = (1 - w) * feats[a, sl] + w * feats[b, sl]
            elif _valid(feats[nearest], deps, fs):
                out[k, sl] = feats[nearest, sl]
            # else: stays zero
        for flag in range(3):
            pa, pb = feats[a, fs.n_coord + flag] > 0.5, feats[b, fs.n_coord + flag] > 0.5
            out[k, fs.n_coord + flag] = 1.0 if (pa and pb) else feats[nearest, fs.n_coord + flag]
    return out


def velocities(seq: np.ndarray, fs: FeatureSpec) -> np.ndarray:
    """(T, F) → (T, n_coord): differences of coordinate features; zero where a part is missing."""
    vel = np.zeros((len(seq), fs.n_coord))
    for sl, deps in _parts_with_deps(fs):
        ok = np.array(
            [_valid(seq[i], deps, fs) and _valid(seq[i - 1], deps, fs) for i in range(1, len(seq))]
        )
        if len(ok):
            vel[1:, sl] = (seq[1:, sl] - seq[:-1, sl]) * ok[:, None]
    return vel


def clip_to_model_input(
    clip: dict[str, np.ndarray],
    fs: FeatureSpec,
    use_velocity: bool = False,
    T: int | None = None,
    dtype: type = np.float32,
) -> np.ndarray:
    """The full shared transform: stored clip → (T, F) or (T, F + n_coord).

    float32 for the model; the golden file uses float64 so TypeScript can be checked at 1e-9.
    """
    filled = fill_short_gaps(clip, fs.max_gap)
    seq = resample(clip_features(filled, fs), filled["t_ms"], fs, T)
    if use_velocity:
        seq = np.concatenate([seq, velocities(seq, fs)], axis=1)
    return seq.astype(dtype)
