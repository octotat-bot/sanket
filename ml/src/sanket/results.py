"""Results table for the README and reports/latest.md, generated only from saved result files.

    python -m sanket.results            # or: make report

Inputs (all committed, small):
  reports/runs/<run>/eval_test.json, eval_val.json, config.yaml, git_sha.txt  (make collect-run)
  reports/export_<name>.json                                                (make export-onnx)
Every number printed comes from these files; nothing is typed by hand. Accuracy CIs are 95%
percentile bootstrap over test videos (10,000 resamples, seed 0).
"""

import argparse
import json
import re
import shutil
from pathlib import Path
from typing import Any

import numpy as np
import yaml

from sanket.paths import REPO_ROOT

REPORTS = REPO_ROOT / "reports"
README = REPO_ROOT / "README.md"
BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"
PAPER_INCLUDE50_TOP1 = 0.945  # Sridhar et al. 2020, best INCLUDE-50 result (CLAUDE.md section 3)
RUN_FILES = ("eval_test.json", "eval_val.json", "config.yaml", "git_sha.txt", "history.json")


def bootstrap_ci(correct: list[int], n_boot: int = 10_000, seed: int = 0) -> tuple[float, float]:
    x = np.asarray(correct, dtype=float)
    rng = np.random.default_rng(seed)
    means = x[rng.integers(0, len(x), size=(n_boot, len(x)))].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    return float(lo), float(hi)


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def load_runs(runs_dir: Path) -> list[dict[str, Any]]:
    out = []
    for d in sorted(p for p in runs_dir.iterdir() if (p / "eval_test.json").exists()):
        test = json.loads((d / "eval_test.json").read_text())
        val = json.loads((d / "eval_val.json").read_text())
        cfg = yaml.safe_load((d / "config.yaml").read_text())["train"]
        out.append(
            {
                "name": d.name,
                "arch": cfg["model"].get("arch", "gru"),
                "test": test,
                "val": val,
                "ci": bootstrap_ci(test["correct"]),
                "git_sha": (d / "git_sha.txt").read_text().strip(),
            }
        )
    return out


def table(runs: list[dict[str, Any]], exports: dict[str, dict[str, Any]]) -> str:
    rows = [
        "| Model | INCLUDE-50 test top-1 (95% CI) | top-5 | val top-1 | Session-independent | "
        "Real-webcam | Paper (best) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        lo, hi = r["ci"]
        rows.append(
            f"| {r['arch']} (`{r['name']}`) | {pct(r['test']['top1'])} ({pct(lo)} to {pct(hi)}), "
            f"n = {r['test']['n']} | {pct(r['test']['top5'])} | {pct(r['val']['top1'])} | "
            f"not measured | not measured | {pct(PAPER_INCLUDE50_TOP1)} |"
        )
    lines = ["\n".join(rows), ""]
    for name, e in sorted(exports.items()):
        size = e["size_bytes"]
        lines.append(
            f"Shipped model `{name}` (from `{e['run_dir']}`): "
            f"ONNX fp32 {size['fp32'] / 1e6:.2f} MB, "
            f"int8 {size['int8'] / 1e6:.2f} MB. On the {e['n']} test videos: PyTorch vs ONNX fp32 "
            f"max logit difference {e['torch_vs_fp32_max_abs_logit_diff']:.1e}; "
            "fp32 vs int8 top-1 "
            f"agreement {pct(e['fp32_vs_int8_top1_agreement'])}; "
            f"accuracy fp32 {pct(e['fp32_acc'])}, "
            f"int8 {pct(e['int8_acc'])}."
        )
    lines.append("")
    lines.append(
        "Session-independent, inferred signer-independent and real-webcam numbers are not measured "
        "yet (Future work). Browser latency and fps are reported only with the device they were "
        "measured on."
    )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--runs", type=Path, default=REPORTS / "runs")
    ap.add_argument("--readme", type=Path, default=README)
    ap.add_argument("--collect", type=Path, help="copy this run dir's result files into --runs")
    args = ap.parse_args()
    if args.collect:
        dest = args.runs / args.collect.name
        dest.mkdir(parents=True, exist_ok=True)
        for f in RUN_FILES:
            shutil.copy2(args.collect / f, dest / f)
        print(f"copied {', '.join(RUN_FILES)} -> {dest}")
        return
    runs = load_runs(args.runs)
    exports = {
        p.stem.removeprefix("export_"): json.loads(p.read_text())
        for p in REPORTS.glob("export_*.json")
    }
    body = table(runs, exports)
    shas = ", ".join(sorted({r["git_sha"][:7] for r in runs}))
    (REPORTS / "latest.md").write_text(
        f"# Results (generated by `make report`)\n\nTraining commits: {shas}\n\n{body}\n"
    )
    text = args.readme.read_text()
    block = f"{BEGIN}\n{body}\n{END}"
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        raise SystemExit(f"{args.readme} has no {BEGIN} … {END} block")
    args.readme.write_text(text)
    print(body)


if __name__ == "__main__":
    main()
