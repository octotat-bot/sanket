"""Which resolution should offline extraction use? (ADR 007)

    uv run python -m sanket.checks.extraction_resolution

The live app's camera delivers about 480 rows (640x480 requested). The Python-vs-browser parity
test shows identical keypoints for identical pixels, so "what the browser sees" for a 480-row
camera = MediaPipe on 480-row frames. For the first 20 `extractor_bench` videos, each extractor
runs on the same decoded frames at native 1080p, downscaled to 720 rows, and downscaled to 480
rows (INTER_AREA, the pipeline's own `resize_to_height`). We compare each with the 480-row run:

* hand rate (share of frames with any hand)
* landmark distance after normalization (aspect-correct, shoulder-centred and -scaled with each
  run's own processed frame size), in **shoulder widths**: hands, and upper-body pose points.
  Only frames where both runs detect the part are compared.
"""

import json
from functools import partial
from typing import Any

import numpy as np

from sanket.checks.sample import MANIFEST, SAMPLES_FILE, VIDEO_CACHE, fetch
from sanket.data.sessions import load_manifest
from sanket.keypoints.extractor import EXTRACTORS
from sanket.keypoints.normalize import body_relative
from sanket.paths import CACHE_DIR, REPORTS_DIR
from sanket.pipeline.extract import extract_video
from sanket.spec import fetch_model, load_spec, model_pins

N_VIDEOS = 20
HEIGHTS: list[int | None] = [None, 720, 480]  # None = native
REFERENCE = 480
UPPER_BODY = [0, 11, 12, 13, 14, 15, 16, 23, 24]  # nose, shoulders, elbows, wrists, hips


def _norm(a: dict[str, np.ndarray], i: int, key: str) -> np.ndarray:
    w, h = (int(v) for v in a["frame_size"])
    return body_relative(a[key][i][:, :3], a["pose"][i][:, :3], w, h)[:, :2]


def compare(ref: dict[str, np.ndarray], other: dict[str, np.ndarray]) -> dict[str, list[float]]:
    out: dict[str, list[float]] = {"hand": [], "pose": []}
    for i in range(min(len(ref["t_ms"]), len(other["t_ms"]))):
        if not (ref["pose_present"][i] and other["pose_present"][i]):
            continue
        try:
            for side in ("left", "right"):
                if ref[f"{side}_present"][i] and other[f"{side}_present"][i]:
                    d = np.linalg.norm(_norm(ref, i, side) - _norm(other, i, side), axis=1)
                    out["hand"].append(float(d.mean()))
            d = np.linalg.norm(
                _norm(ref, i, "pose")[UPPER_BODY] - _norm(other, i, "pose")[UPPER_BODY], axis=1
            )
            out["pose"].append(float(d.mean()))
        except ValueError:  # degenerate shoulders in one run: frame not comparable
            continue
    return out


def main() -> None:
    models = {p.name: fetch_model(p, CACHE_DIR / "models") for p in model_pins(load_spec())}
    paths = json.loads(SAMPLES_FILE.read_text())["extractor_bench"][:N_VIDEOS]
    fetch(paths, load_manifest(MANIFEST))

    results: dict[str, Any] = {}
    for name, cls in EXTRACTORS.items():
        hand_rate: dict[str, list[float]] = {str(h): [] for h in HEIGHTS}
        frames: dict[str, list[int]] = {str(h): [] for h in HEIGHTS}
        dist: dict[str, dict[str, list[float]]] = {
            str(h): {"hand": [], "pose": []} for h in HEIGHTS if h != REFERENCE
        }
        for n, rel in enumerate(paths, 1):
            runs = {}
            for h in HEIGHTS:
                a, _ = extract_video(VIDEO_CACHE / rel, partial(cls, models), None, target_height=h)
                runs[str(h)] = a
                anyh = a["left_present"] | a["right_present"]
                hand_rate[str(h)].append(float(anyh.sum()))
                frames[str(h)].append(len(anyh))
            for h in HEIGHTS:
                if h == REFERENCE:
                    continue
                c = compare(runs[str(REFERENCE)], runs[str(h)])
                dist[str(h)]["hand"] += c["hand"]
                dist[str(h)]["pose"] += c["pose"]
            print(f"{name} [{n}/{len(paths)}] {rel}")

        def q(xs: list[float], p: float) -> float:
            return float(np.percentile(xs, p)) if xs else float("nan")

        results[name] = {
            "hand_rate": {k: sum(v) / sum(frames[k]) for k, v in hand_rate.items()},
            "vs_480": {
                k: {
                    part: {"median": q(v, 50), "p90": q(v, 90), "n": len(v)}
                    for part, v in d.items()
                }
                for k, d in dist.items()
            },
        }

    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "phase1_extraction_resolution.json").write_text(
        json.dumps(results, indent=2) + "\n"
    )
    label = {"None": "native 1080p", "720": "720 rows", "480": "480 rows"}
    lines = [
        "# Offline extraction resolution vs the browser's 480-row input (generated)",
        "",
        f"Generated by `python -m sanket.checks.extraction_resolution` on the first {N_VIDEOS} "
        "`extractor_bench` INCLUDE videos. Distances are mean landmark distance after normalization "
        "(aspect-correct, shoulder-centred, shoulder-width units), compared with the **480-row** run "
        "(= what MediaPipe sees from a 640x480 camera). Only frames where both runs detect the part.",
        "",
    ]
    for name, r in results.items():
        lines += [
            f"## {name}",
            "",
            "| extraction height | hand rate | hands vs 480: median / p90 | upper body vs 480: median / p90 |",
            "|---|---|---|---|",
        ]
        for h in HEIGHTS:
            k = str(h)
            if h == REFERENCE:
                lines.append(
                    f"| {label[k]} | {100 * r['hand_rate'][k]:.1f}% | (reference) | (reference) |"
                )
            else:
                hd, pd = r["vs_480"][k]["hand"], r["vs_480"][k]["pose"]
                lines.append(
                    f"| {label[k]} | {100 * r['hand_rate'][k]:.1f}% | {hd['median']:.3f} / {hd['p90']:.3f} (n={hd['n']}) "
                    f"| {pd['median']:.3f} / {pd['p90']:.3f} (n={pd['n']}) |"
                )
        lines.append("")
    (REPORTS_DIR / "phase1_extraction_resolution.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
