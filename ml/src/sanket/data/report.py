"""reports/data.md: what the Phase 1 extraction produced (generated, never hand-edited).

    uv run python -m sanket.data.report [--config configs/extract.yaml]

Reads the extraction log (`_log.jsonl`) and the official splits. Covers class counts,
sequence length distribution, detection rates, split sizes (and what's missing), errors,
the low-hand-detection review list, and duplicate videos found by sha256.
"""

import argparse
import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from sanket.data.keypoint_index import index_npz, load_split_index
from sanket.data.splits import DATASETS, SPLITS, load_split, video_key
from sanket.paths import REPO_ROOT, REPORTS_DIR
from sanket.pipeline.extract import Config


def latest_records(log_path: Path) -> list[dict[str, Any]]:
    """Last record per video (a rerun after an error overrides the error)."""
    by_path: dict[str, dict[str, Any]] = {}
    for line in log_path.read_text().splitlines():
        r = json.loads(line)
        by_path[r["path"]] = r
    return sorted(by_path.values(), key=lambda r: r["path"])


def _q(values: list[float], q: float) -> float:
    s = sorted(values)
    return s[min(len(s) - 1, round(q * (len(s) - 1)))] if s else float("nan")


def build(out_dir: Path, records: list[dict[str, Any]]) -> tuple[str, dict[str, Any]]:
    ok = [r for r in records if r["status"] == "ok"]
    err = [r for r in records if r["status"] == "error"]
    lengths = [r["n_frames"] for r in ok]
    per_class = Counter(r["label"] for r in ok)
    dup: dict[str, list[str]] = defaultdict(list)
    for r in ok + err:
        if "sha256" in r:
            dup[r["sha256"]].append(r["path"])
    dups = {h: ps for h, ps in dup.items() if len(ps) > 1}
    npz = index_npz(out_dir)
    splits = {(ds, s): load_split_index(ds, s, out_dir, npz) for ds in DATASETS for s in SPLITS}

    def rate(k: str) -> float:
        n = sum(r["n_frames"] for r in ok)
        return sum(r[k] * r["n_frames"] for r in ok) / n if n else float("nan")

    summary: dict[str, Any] = {
        "videos_ok": len(ok),
        "videos_error": len(err),
        "classes": len(per_class),
        "frames": sum(lengths),
        "length": {
            "min": min(lengths, default=0),
            "p05": _q(lengths, 0.05),
            "median": statistics.median(lengths) if lengths else 0,
            "p95": _q(lengths, 0.95),
            "max": max(lengths, default=0),
        },
        "rates": {
            k: rate(k)
            for k in ("rate_pose", "rate_left", "rate_right", "rate_any_hand", "rate_both_hands")
        },
        "fps": dict(Counter(round(r["fps"], 3) for r in ok)),
        "resolution": dict(Counter(f"{r['width']}x{r['height']}" for r in ok)),
        "splits": {
            f"{ds}/{s}": {"loaded": len(ix.items), "missing": len(ix.missing)}
            for (ds, s), ix in splits.items()
        },
        "duplicates": dups,
        "review": [r["path"] for r in ok if r["rate_any_hand"] < 0.05],
    }
    # INCLUDE-50 train only: the population T is chosen from (ADR 008), never val or test.
    train_keys = {video_key(e) for e in load_split("include50", "train")}
    tr = [r for r in ok if video_key(r["path"]) in train_keys]
    tr_len = [r["n_frames"] for r in tr]
    tr_sec = [r["n_frames"] / r["fps"] for r in tr if r.get("fps")]
    summary["include50_train_length"] = {
        "n": len(tr),
        "frames": {q: _q(tr_len, v) for q, v in (("p10", 0.1), ("p50", 0.5), ("p90", 0.9))},
        "seconds": {
            q: round(_q(tr_sec, v), 3) for q, v in (("p10", 0.1), ("p50", 0.5), ("p90", 0.9))
        },
    }

    lines = [
        "# Phase 1 data report (generated)",
        "",
        "Generated by `python -m sanket.data.report` from the extraction log. Do not edit by hand.",
        "",
        f"- Videos extracted: {len(ok)}. Errors: {len(err)}. Classes with data: {len(per_class)}. Frames: {sum(lengths)}",
        f"- fps: {summary['fps']}. Resolution: {summary['resolution']}",
        "- Sequence length (frames): "
        + ", ".join(f"{k} {v:g}" for k, v in summary["length"].items()),
        "- Detection rates (pooled over frames): "
        + ", ".join(
            f"{k.removeprefix('rate_')} {100 * v:.1f}%" for k, v in summary["rates"].items()
        ),
        "",
        "## INCLUDE-50 train lengths (for T, ADR 008)",
        "",
        f"- {summary['include50_train_length']['n']} videos. Frames: "
        + ", ".join(f"{k} {v:g}" for k, v in summary["include50_train_length"]["frames"].items())
        + ". Seconds: "
        + ", ".join(f"{k} {v:g}" for k, v in summary["include50_train_length"]["seconds"].items()),
        "",
        "## Splits",
        "",
        "| split | loaded | missing keypoints |",
        "|---|---|---|",
        *[f"| {k} | {v['loaded']} | {v['missing']} |" for k, v in summary["splits"].items()],
        "",
        "## Class counts (videos with keypoints)",
        "",
        f"- min {min(per_class.values(), default=0)}, median {statistics.median(per_class.values()) if per_class else 0}, "
        f"max {max(per_class.values(), default=0)}",
        "- Fewest: "
        + ", ".join(
            f"{c} ({n})" for c, n in sorted(per_class.items(), key=lambda x: (x[1], x[0]))[:10]
        ),
        "",
        "## Errors",
        "",
        *([f"- `{r['path']}`: {r['error']}" for r in err] or ["- none"]),
        "",
        "## Review list (any hand in < 5% of frames; kept, not dropped)",
        "",
        *([f"- `{p}`" for p in summary["review"]] or ["- none"]),
        "",
        "## Duplicate videos (identical sha256)",
        "",
        *([f"- {', '.join(f'`{p}`' for p in ps)}" for ps in dups.values()] or ["- none"]),
        "",
    ]
    return "\n".join(lines), summary


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--config", type=Path, default=REPO_ROOT / "ml" / "configs" / "extract.yaml")
    ap.add_argument("--out", type=Path, default=REPORTS_DIR)
    args = ap.parse_args()
    cfg = Config.load(args.config)
    md, summary = build(cfg.out_dir, latest_records(cfg.out_dir / "_log.jsonl"))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "data.md").write_text(md)
    (args.out / "data.json").write_text(json.dumps(summary, indent=2, default=str) + "\n")
    print(md)


if __name__ == "__main__":
    main()
